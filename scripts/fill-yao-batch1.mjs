const ALL_HEX_DATA = { 2: HEX_2, 3: HEX_3, 4: HEX_4, 5: HEX_5 }

const data = JSON.parse(readFileSync(JSON_PATH, 'utf-8'))
let updated = 0

for (const hex of data) {
  const hexData = ALL_HEX_DATA[hex.id]
  if (!hexData) continue

  for (let i = 0; i < hex.yaoLines.length; i++) {
    const yao = hex.yaoLines[i]
    const position = yao.position
    const newData = hexData[position]
    if (!newData) continue

    yao.originalText = newData.o
    yao.explanation = newData.e
    yao.modernMeaning = newData.m
    yao.deepMeaning = newData.d
    updated++
  }
}

writeFileSync(JSON_PATH, JSON.stringify(data, null, 2) + '\n', 'utf-8')
console.log(`Updated ${updated} yao lines across hexagrams ${Object.keys(ALL_HEX_DATA).join(', ')}`)
console.log(`File: ${JSON_PATH}`)
